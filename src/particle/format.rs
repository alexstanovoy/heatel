/// KV3's generic format, which predates every `vpcf` one.
const GENERIC: [u8; 16] = [
    0x7c, 0x16, 0x12, 0x74, 0xe9, 0x06, 0x98, 0x46, 0xaf, 0xf2, 0xe6, 0x3e, 0xb5, 0x90, 0x37, 0xe7,
];

/// The format number of GUID `guid`: 0 for the generic format, `u32::MAX` (current) for one this
/// crate does not know, which a newer game writes.
pub(super) fn format_number(guid: &[u8; 16]) -> u32 {
    if *guid == GENERIC {
        return 0;
    }
    FORMATS
        .iter()
        .find_map(|(id, number)| (id == guid).then_some(*number))
        .unwrap_or(u32::MAX)
}
